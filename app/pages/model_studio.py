from __future__ import annotations

from pathlib import Path

import streamlit as st

from app.styles import hero
from app.styles import section_heading
from inference.generate_faces import FaceModelUnavailableError, generate_faces, save_face_images


def render() -> None:
    hero("AI Model Studio", "Generate synthetic portraits from the independently trained face GAN.", "Model laboratory")
    checkpoint = "checkpoints/face_generator.pth"
    if not Path(checkpoint).exists():
        st.info(
            "The face-generation GAN has not been trained. No generated faces are displayed. "
            "Train it with the configured real-face dataset before generating."
        )
    count = st.slider("Number of faces", 1, 8, 2)
    seed = st.number_input("Seed", min_value=0, value=42)
    if st.button("Generate faces", type="primary"):
        try:
            faces = generate_faces(checkpoint, count=count, seed=int(seed))
            paths = save_face_images(faces, seed=int(seed))
            display_faces = [
                ((face.detach().cpu() + 1.0) / 2.0).clamp(0.0, 1.0).permute(1, 2, 0).numpy()
                for face in faces
            ]
            st.image(display_faces, width=220)
            st.session_state["face_paths"] = paths
        except FaceModelUnavailableError as error:
            st.info(str(error))
        except ValueError as error:
            st.error(str(error))
    paths = st.session_state.get("face_paths", [])
    if paths:
        section_heading("Download portraits", "These PNGs were generated by the trained face checkpoint.")
        columns = st.columns(min(len(paths), 4))
        for index, path in enumerate(paths):
            with columns[index % len(columns)]:
                st.download_button(
                    f"Download {index + 1:02d}",
                    data=path.read_bytes(),
                    file_name=path.name,
                    mime="image/png",
                    key=str(path),
                    width="stretch",
                )
    st.markdown(
        """
        **Face model**
        - A dedicated face dataset and preprocessing pipeline
        - An independent face generator and discriminator
        - Separate checkpoints and outputs under `checkpoints/` and `outputs/faces/`
        """
    )
